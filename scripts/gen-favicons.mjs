// Regenerates src/dashboard/icons-data.ts (the dashboard's favicon assets) from the Z geometry below.
// Needs puppeteer-core and a Chrome binary (not project dependencies):
//   CHROME=/usr/bin/google-chrome node scripts/gen-favicons.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import puppeteer from "puppeteer-core";

// 512 box. The white band runs from the top-right to the bottom-left, the two bars are a blue to teal gradient.
const z = k => {
  // k = 1 is the large icon, k > 1 the bolder small-size variant (scaled about the centre)
  const t = (x, y) => `${(256 + (x - 256) * k).toFixed(1)} ${(258 + (y - 258) * k).toFixed(1)}`;
  const P = pts => "M" + pts.map(p => t(...p)).join(" L") + " Z";
  const top = P([[121, 152], [167, 106], [394, 106], [317, 192], [121, 192]]);
  const band = P([[394, 106], [394, 180], [187, 410], [121, 410]]);
  const bottom = P([[264, 324], [394, 324], [394, 364], [348, 410], [187, 410]]);
  const [x1, y1] = t(121, 106).split(" "), [x2, y2] = t(394, 410).split(" ");
  return `<defs><linearGradient id="g" gradientUnits="userSpaceOnUse" x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"><stop offset="0" stop-color="#2f7cff"/><stop offset=".55" stop-color="#22a8e8"/><stop offset="1" stop-color="#19dcc4"/></linearGradient></defs>` +
    `<path d="${band}" fill="#ffffff"/><path d="${top}" fill="url(#g)"/><path d="${bottom}" fill="url(#g)"/>`;
};
const svg = (k, border) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512"><rect width="512" height="512" rx="112" fill="#0b1424"/>${border ? '<rect x="2" y="2" width="508" height="508" rx="110" fill="none" stroke="#ffffff" stroke-opacity=".08" stroke-width="4"/>' : ""}${z(k)}</svg>`;
const big = svg(1, true), small = svg(1.18, false);

const browser = await puppeteer.launch({ executablePath: process.env.CHROME || "/usr/bin/google-chrome", args: ["--no-sandbox", "--disable-gpu"], headless: true });
const page = await browser.newPage();
async function png(markup, size) {
  await page.setViewport({ width: size, height: size, deviceScaleFactor: 1 });
  await page.setContent(`<html><body style="margin:0;background:transparent">${markup.replace('width="512" height="512"', `width="${size}" height="${size}"`)}</body></html>`);
  return Buffer.from(await page.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: size, height: size } }));
}
const p16 = await png(small, 16), p32 = await png(small, 32);
const files = { "favicon-16.png": p16, "favicon-32.png": p32, "apple-touch-icon.png": await png(big, 180), "icon-192.png": await png(big, 192), "icon-512.png": await png(big, 512) };
await browser.close();

// favicon.ico = ICONDIR + two PNG entries (16 and 32 px)
const ico = Buffer.alloc(6 + 32); ico.writeUInt16LE(1, 2); ico.writeUInt16LE(2, 4);
[[16, p16, 38], [32, p32, 38 + p16.length]].forEach(([size, data, off], i) => {
  const o = 6 + i * 16; ico[o] = size; ico[o + 1] = size; ico.writeUInt16LE(1, o + 4); ico.writeUInt16LE(32, o + 6); ico.writeUInt32LE(data.length, o + 8); ico.writeUInt32LE(off, o + 12);
});
const icoFile = Buffer.concat([ico, p16, p32]);

const out = `// Dashboard icons: a rounded navy square with the blue-to-teal "Z" (top bar, white diagonal, bottom bar) from the sidebar logo.
// GENERATED by scripts/gen-favicons.mjs (headless Chrome renders the SVG; the .ico is a 16 + 32 px PNG-in-ICO). Static data, no build step.
// The SVG favicon is the bolder small-size variant; the 180/192/512 px PNGs use the large artwork.
export const FAVICON_SVG = ${JSON.stringify(small)};
export const ICON_PNG_B64: Readonly<Record<string, string>> = {
${Object.entries(files).map(([n, d]) => `  ${JSON.stringify(n)}: "${d.toString("base64")}"`).join(",\n")}
};
export const FAVICON_ICO_B64 = "${icoFile.toString("base64")}";
`;
writeFileSync(fileURLToPath(new URL("../src/dashboard/icons-data.ts", import.meta.url)), out);
console.log("wrote icons-data.ts", out.length, "bytes");
